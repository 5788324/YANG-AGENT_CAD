#!/usr/bin/env python3
"""Run existing project gates on any OS. Static PASS is not AutoCAD runtime PASS."""
from __future__ import annotations
import argparse
import datetime as dt
import json
import os
import shutil
from pathlib import Path
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[1]

def main() -> int:
    parser = argparse.ArgumentParser(description='Run YangCAD source and policy tests (not Windows runtime).')
    parser.add_argument('--output', default=None, help='Optional JSON report path (e.g. artifacts/ci-static-report.json).')
    args = parser.parse_args()
    scripts = [ROOT / 'tools/verify_source.py', ROOT / 'tools/verify_release_source.py']
    scripts.extend(sorted((ROOT / 'tools').glob('test_*_policy.py')))
    # Clean Python bytecode generated by earlier invocations; source validation forbids it.
    for cache in ROOT.rglob('__pycache__'):
        if cache.is_dir(): shutil.rmtree(cache)
    for cache in ROOT.rglob('*.pyc'):
        if cache.is_file(): cache.unlink()
    child_env=dict(os.environ, PYTHONDONTWRITEBYTECODE='1')
    reports=[]
    for script in scripts:
        start=time.monotonic()
        run=subprocess.run([sys.executable, str(script)], cwd=ROOT, text=True,
                           stdout=subprocess.PIPE, stderr=subprocess.STDOUT, errors='replace', env=child_env)
        item={'script':script.relative_to(ROOT).as_posix(),
              'status':'PASS' if run.returncode==0 else 'FAIL',
              'exit_code':run.returncode,'duration_seconds':round(time.monotonic()-start,3),
              'output':run.stdout[-12000:]}
        reports.append(item)
        print(f"{item['status']:4} {item['script']} ({item['duration_seconds']:.2f}s)",flush=True)
        if run.returncode!=0:
            print(run.stdout[-4000:],flush=True)
    summary={'schema':'yangcad-static-report/1.0',
             'generated_utc':dt.datetime.now(dt.timezone.utc).isoformat(),
             'interpretation':'STATIC ONLY; no Windows/AutoCAD/Civil/Revit execution',
             'tested_count':len(reports),'passed_count':sum(x['status']=='PASS' for x in reports),
             'failed_count':sum(x['status']=='FAIL' for x in reports),
             'checks':reports}
    if args.output:
        output=Path(args.output)
        if not output.is_absolute(): output=ROOT/output
        output.parent.mkdir(parents=True,exist_ok=True)
        output.write_text(json.dumps(summary,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')
    print(f"Result {summary['passed_count']}/{summary['tested_count']} PASS; STATIC ONLY",flush=True)
    return 1 if summary['failed_count'] else 0

if __name__=='__main__': raise SystemExit(main())
